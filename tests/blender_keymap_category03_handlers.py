class HandlerCases:
    def __init__(self, steps, receipt, record, window, area, exporter, *, probe=False):
        import bpy
        self.bpy, self.steps, self.receipt, self.record = bpy, steps, receipt, record
        self.window, self.area, self.exporter = window, area, exporter
        self.configs = bpy.context.window_manager.keyconfigs
        self.probe, self.owned, self.sources = probe, [], []
        self.values = {}
        self.scope_names = {row['scope']['name'] for row in BINDINGS.values()} | {'Image', 'Mesh'}

    def region(self):
        return next(r for r in self.area.regions if r.type == 'WINDOW')

    def context(self):
        return self.bpy.context.temp_override(window=self.window, area=self.area, region=self.region())

    def event(self, key, value='PRESS', *, dx=0, dy=0, **mods):
        r = self.region()
        x, y = self.values.get('point', (r.width // 2, r.height // 2))
        self.window.event_simulate(type=key, value=value, x=r.x+x+dx, y=r.y+y+dy, **mods)

    def press(self, key, **mods):
        self.event(key, **mods)
        self.event(key, 'RELEASE', **mods)

    def capture(self, keymap):
        return self.exporter._capture_map(keymap, self.bpy.types.OperatorProperties)

    def start(self):
        seen = set()
        for role in ('default', 'active'):
            for km in getattr(self.configs, role).keymaps:
                if km.name in self.scope_names and km.as_pointer() not in seen:
                    self.sources.append((km, self.capture(km)))
                    seen.add(km.as_pointer())
        if self.probe:
            for ledger_id, row in BINDINGS.items():
                scope, event = row['scope'], row['event']
                km = self.configs.addon.keymaps.new(name=scope['name'], space_type=scope['space_type'],
                                                   region_type=scope['region_type'])
                kwargs = {name: event[name] for name in
                          ('type', 'value', 'any', 'shift', 'ctrl', 'alt', 'oskey', 'key_modifier', 'repeat', 'direction')}
                item = km.keymap_items.new(row['target'], **kwargs)
                self.owned.append((km, item))
                for name, value in row['properties'].items():
                    setattr(item.properties, name, value)
        self.configs.update()
        self.receipt['handler_proof'] = {
            'stage': 'owned_exact_addon' if self.probe else 'readonly_reference_or_factory',
            'ledger_ids': list(BINDINGS), 'owned_count': len(self.owned),
            'production_capability_enabled': False,
            'merged_before': [self.capture(km) for km in self.configs.user.keymaps if km.name in self.scope_names]}
        self.record('handler_probe_ready')

    def cleanup(self):
        while self.owned:
            km, item = self.owned.pop()
            km.keymap_items.remove(item)
        self.configs.update()
        assert all(self.capture(km) == before for km, before in self.sources), 'Foreign source fields/order changed'
        if 'handler_proof' in self.receipt:
            self.receipt['handler_proof']['owned_removed'] = True
            self.receipt['handler_proof']['foreign_source_fields_and_order_unchanged'] = True

    def setup(self, kind, subtract=False):
        import bmesh
        from mathutils import Quaternion
        bpy = self.bpy
        self.values = {'kind': kind}
        self.area.type = 'VIEW_3D'
        with self.context():
            if bpy.context.object and bpy.context.object.mode != 'OBJECT':
                bpy.ops.object.mode_set(mode='OBJECT')
            for obj in bpy.context.scene.objects:
                obj.select_set(False)
            if kind in ('uv', 'mesh'):
                bpy.ops.mesh.primitive_grid_add(x_subdivisions=4, y_subdivisions=4, size=2)
                obj = bpy.context.object
                self.values['object_name'] = obj.name
                bpy.ops.object.mode_set(mode='EDIT')
                bpy.context.scene.tool_settings.mesh_select_mode = (True, False, False)
                bpy.ops.mesh.select_all(action='SELECT' if kind == 'uv' else 'DESELECT')
                bm = bmesh.from_edit_mesh(obj.data)
                bm.verts.ensure_lookup_table()
                if kind == 'mesh':
                    bm.verts[0].select_set(True)
                    bm.select_history.add(bm.verts[0])
                    self.values['target_vertex'] = len(bm.verts)-1
                else:
                    uv = bm.loops.layers.uv.verify()
                    bpy.context.scene.tool_settings.use_uv_select_sync = False
                    for face in bm.faces:
                        face.select_set(True)
                        for loop in face.loops:
                            loop[uv].select = subtract
                bmesh.update_edit_mesh(obj.data)
            else:
                obj = bpy.data.objects.get('Category Handler Cube')
                if obj is None:
                    bpy.ops.mesh.primitive_cube_add()
                    obj = bpy.context.object
                    obj.name = 'Category Handler Cube'
                obj.location = (0, 0, 0)
                # A factory Cube and earlier UV grids otherwise overlap this
                # target and make Ctrl-click subtraction indeterminate.
                for other in bpy.context.scene.objects:
                    other.hide_set(other != obj)
                obj.hide_set(False)
                obj.select_set(subtract)
                bpy.context.view_layer.objects.active = obj
                self.values['object_name'] = obj.name
            bpy.ops.wm.tool_set_by_id(name='builtin.select_box')
        view = self.area.spaces.active.region_3d
        view.view_rotation = Quaternion((1, 0, 0, 0))
        view.view_location = (0, 0, 0)
        view.view_distance = 10
        view.view_perspective = 'ORTHO'
        if kind == 'uv':
            self.area.type = 'IMAGE_EDITOR'
            self.area.ui_type = 'UV'
            with self.context():
                bpy.ops.wm.tool_set_by_id(name='builtin.select_box')
                bpy.ops.image.view_all()

    def aim(self, shortest=False):
        import bmesh
        kind, bpy = self.values['kind'], self.bpy
        obj = bpy.data.objects[self.values['object_name']]
        r = self.region()
        if kind == 'uv':
            bm = bmesh.from_edit_mesh(obj.data)
            uv = bm.loops.layers.uv.active
            loops = [(f.index, i, tuple(loop[uv].uv)) for f in bm.faces for i, loop in enumerate(f.loops)]
            target = max(loops, key=lambda row: sum(row[2])) if shortest else min(loops, key=lambda row: sum((n-.5)**2 for n in row[2]))
            if shortest:
                for f in bm.faces:
                    for loop in f.loops:
                        loop[uv].select = sum(loop[uv].uv) < .01
                bmesh.update_edit_mesh(obj.data)
            self.values['point'] = tuple(map(int, r.view2d.view_to_region(*target[2], clip=False)))
            self.values['target_uv'] = target
        elif kind == 'mesh':
            from bpy_extras.view3d_utils import location_3d_to_region_2d
            bm = bmesh.from_edit_mesh(obj.data)
            bm.verts.ensure_lookup_table()
            position = obj.matrix_world @ bm.verts[self.values['target_vertex']].co
            point = location_3d_to_region_2d(r, self.area.spaces.active.region_3d, position)
            assert point is not None
            self.values['point'] = tuple(map(int, point))
        else:
            self.values['point'] = (r.width//2, r.height//2)
        x, y = self.values['point']
        assert 0 <= x < r.width and 0 <= y < r.height, 'Target outside owned WINDOW region'
        self.event('MOUSEMOVE', 'NOTHING')

    def read(self):
        import bmesh
        bpy, kind = self.bpy, self.values['kind']
        result = {'history': [o.bl_idname for o in bpy.context.window_manager.operators],
                  'modal_operators_observable': hasattr(self.window, 'modal_operators'),
                  'modal_operators': [o.bl_idname for o in getattr(self.window, 'modal_operators', ())]}
        if kind == 'uv':
            bm = bmesh.from_edit_mesh(bpy.data.objects[self.values['object_name']].data)
            uv = bm.loops.layers.uv.active
            result['selected'] = [[f.index, i] for f in bm.faces for i, loop in enumerate(f.loops) if loop[uv].select]
            r = self.region()
            result['view'] = {'center': list(r.view2d.region_to_view(r.width/2, r.height/2)),
                              'zoom': list(self.area.spaces.active.zoom)}
        else:
            if kind == 'mesh':
                bm = bmesh.from_edit_mesh(bpy.data.objects[self.values['object_name']].data)
                result['selected'] = [v.index for v in bm.verts if v.select]
            else:
                result['selected'] = sorted(o.name for o in bpy.context.selected_objects)
            v = self.area.spaces.active.region_3d
            result['view'] = {'location': list(v.view_location), 'rotation': list(v.view_rotation), 'distance': v.view_distance}
        return result

    def case(self, label, kind='object', *, mods=None, gesture='drag', circle=False, subtract=False, shortest=False):
        mods = mods or {}
        values = {}
        key = 'LEFTMOUSE' if gesture == 'subtract' else 'MIDDLEMOUSE'
        def setup():
            self.setup(kind, subtract=subtract)
        def aim():
            self.aim(shortest=shortest)
        def begin():
            values['before'] = self.read()
            if gesture in ('click_move', 'double_drag'):
                self.press(key, **mods)
            if gesture != 'click_move':
                self.event(key, **mods)
        def first_move():
            self.event('MOUSEMOVE', 'NOTHING', dx=8, dy=3, **mods)
        def move():
            self.event('MOUSEMOVE', 'NOTHING', dx=70, dy=30, **mods)
        def release():
            if gesture != 'click_move':
                self.event(key, 'RELEASE', dx=70 if gesture != 'subtract' else 0,
                           dy=30 if gesture != 'subtract' else 0, **mods)
        def observe():
            values['after_gesture'] = self.read()
            if circle and kind != 'uv':
                # wait_for_input=True can require a separate brush click after
                # entry. Record the middle gesture independently before this.
                self.event('MOUSEMOVE', 'NOTHING')
                self.press('LEFTMOUSE', **mods)
        def before_cancel():
            values['after_brush'] = self.read()
            self.press('ESC')
        def end():
            row = {'case': label, 'kind': kind, 'gesture': gesture, 'modifiers': mods,
                   'target_object': self.values['object_name'],
                   'before': values['before'], 'after_gesture': values['after_gesture'],
                   'after_brush': values['after_brush'], 'after_cancel': self.read()}
            if circle:
                with self.context():
                    module = bpy.ops.uv if kind == 'uv' else bpy.ops.view3d
                    x, y = self.values['point']
                    result = module.select_circle('EXEC_DEFAULT', x=x, y=y, radius=25,
                                                  mode='SUB' if subtract else 'ADD', wait_for_input=False)
                row['direct_control'] = {'result': sorted(result), 'after': self.read(),
                                         'method': 'fixture control, not native dispatch'}
            if gesture == 'subtract' and kind == 'object':
                with self.context():
                    result = bpy.ops.view3d.select('EXEC_DEFAULT', location=self.values['point'], deselect=True)
                row['direct_control'] = {'result': sorted(result), 'after': self.read(),
                                         'method': 'fixture control, not native dispatch'}
            self.receipt['dispatch'].append(row)
            self.record(label)
        bpy = self.bpy
        self.steps.extend((setup, lambda: None, aim, begin))
        if gesture != 'subtract':
            self.steps.extend((first_move, move))
        self.steps.extend((release, observe, before_cancel, end))

    def append(self):
        self.steps.append(self.start)
        self.case('handler_middle_click_then_move', gesture='click_move')
        self.case('handler_middle_drag')
        self.case('handler_middle_double_drag', gesture='double_drag')
        for kind in ('object', 'uv'):
            self.case('handler_circle_'+kind+'_add', kind, mods={'shift': True}, circle=True)
            self.case('handler_circle_'+kind+'_subtract', kind, mods={'ctrl': True}, circle=True, subtract=True)
        self.case('handler_ctrl_click_object_subtract', mods={'ctrl': True}, gesture='subtract', subtract=True)
        self.case('handler_ctrl_click_mesh_shortest_path', 'mesh', mods={'ctrl': True}, gesture='subtract', shortest=True)
        self.case('handler_ctrl_click_uv_shortest_path', 'uv', mods={'ctrl': True}, gesture='subtract', shortest=True)
        self.steps.append(self.cleanup)
        return self


